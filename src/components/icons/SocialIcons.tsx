/**
 * Whether a platform string has a brand glyph.
 *
 * The social engine's `PlatformId` is a superset of `SocialPlatform`: it includes `blog`, which
 * is a publishing surface on this site rather than a social network, and has no logo. Callers
 * iterating engine platforms narrow through this instead of casting.
 */
export function hasSocialIcon(platform: string): platform is SocialPlatform {
  return Object.prototype.hasOwnProperty.call(PATHS, platform);
}

/** One icon, chosen at runtime. The video outro maps over `SOCIALS` and can't pick a component. */
export function SocialIcon({ platform, ...props }: SocialIconProps & { platform: SocialPlatform }) {
  return <Glyph d={PATHS[platform]} {...props} />;
}

/** Same, but tolerant of a platform with no glyph — renders nothing rather than crashing. */
export function MaybeSocialIcon({ platform, ...props }: SocialIconProps & { platform: string }) {
  if (!hasSocialIcon(platform)) return null;
  return <Glyph d={PATHS[platform]} {...props} />;
}

